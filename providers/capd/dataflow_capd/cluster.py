from __future__ import annotations

import ipaddress
from dataclasses import dataclass

import pulumi
import pulumi_kubernetes as k8s

from .cni import render_kindnet

# API groups
_CLUSTER_API_GROUP = "cluster.x-k8s.io"
_CONTROLPLANE_API_GROUP = "controlplane.cluster.x-k8s.io"
_BOOTSTRAP_API_GROUP = "bootstrap.cluster.x-k8s.io"
_INFRA_API_GROUP = "infrastructure.cluster.x-k8s.io"

# CNI label
CNI_LABEL_KEY = "dataflow.io/cni"
CNI_LABEL_VALUE = "kindnet"

# KubeadmControlPlane / KubeadmConfigTemplate settings
CERT_SANS = ["localhost", "127.0.0.1", "0.0.0.0", "host.docker.internal"]
KUBELET_EVICTION_VALUE = "nodefs.available<0%,nodefs.inodesFree<0%,imagefs.available<0%"


def _kubelet_extra_args() -> list[dict]:
    return [{"name": "eviction-hard", "value": KUBELET_EVICTION_VALUE}]


def _name_of(res: pulumi.Resource) -> pulumi.Output[str]:
    return res.metadata.apply(lambda m: m["name"])  # type: ignore[attr-defined]


@dataclass(frozen=True)
class ClusterArgs:
    name: str
    namespace: str
    kubernetes_version: str
    pod_cidr: str
    service_cidr: str
    control_plane_replicas: int
    worker_replicas: int

    def __post_init__(self) -> None:
        if not self.name:
            raise ValueError("name must not be empty")
        if not self.kubernetes_version.startswith("v"):
            raise ValueError("kubernetes_version must start with 'v'")
        if self.control_plane_replicas <= 0 or self.control_plane_replicas % 2 == 0:
            raise ValueError("control_plane_replicas must be a positive odd number")
        if self.worker_replicas < 0:
            raise ValueError("worker_replicas must be non-negative")
        for field_name, value in [("pod_cidr", self.pod_cidr), ("service_cidr", self.service_cidr)]:
            if "/" not in value:
                raise ValueError(f"{field_name} must be a CIDR (e.g. 192.168.0.0/16)")
            try:
                ipaddress.ip_network(value, strict=False)
            except ValueError as exc:
                raise ValueError(f"{field_name} is not a valid CIDR: {exc}") from exc


class Cluster(pulumi.ComponentResource):
    cluster_name: pulumi.Output[str]
    namespace: pulumi.Output[str]
    kubeconfig_secret_name: pulumi.Output[str]

    def __init__(
        self,
        name: str,
        args: ClusterArgs,
        opts: pulumi.ResourceOptions | None = None,
    ) -> None:
        super().__init__("dataflow:capd:Cluster", name, None, opts)
        child_opts = pulumi.ResourceOptions(parent=self)

        # Namespace
        ns = k8s.core.v1.Namespace(
            args.namespace,
            metadata={"name": args.namespace},
            opts=child_opts,
        )
        ns_name = _name_of(ns)

        def _namespaced(extra: dict | None = None) -> dict:
            meta: dict = {"namespace": ns_name}
            if extra:
                meta.update(extra)
            return meta

        # DockerCluster
        # import is deferred so tests can patch before importing
        import pulumi_capd as capd  # type: ignore[import-not-found]  # generated by make sdk-init
        import pulumi_capi as capi  # type: ignore[import-not-found]  # generated by make sdk-init

        dc = capd.infrastructure.v1beta2.DockerCluster(
            args.name,
            metadata={**_namespaced(), "name": args.name},
            spec={},
            opts=child_opts,
        )

        # DockerMachineTemplate — control plane (auto-named, replace on spec change)
        cp_dmt = capd.infrastructure.v1beta2.DockerMachineTemplate(
            f"{args.name}-control-plane",
            metadata=_namespaced(),
            spec={"template": {"spec": {}}},
            opts=pulumi.ResourceOptions(parent=self, replace_on_changes=["spec"]),
        )

        # DockerMachineTemplate — workers (auto-named, replace on spec change)
        worker_dmt = capd.infrastructure.v1beta2.DockerMachineTemplate(
            f"{args.name}-md-0",
            metadata=_namespaced(),
            spec={"template": {"spec": {}}},
            opts=pulumi.ResourceOptions(parent=self, replace_on_changes=["spec"]),
        )

        # KubeadmControlPlane
        kcp = capi.controlplane.v1beta2.KubeadmControlPlane(
            f"{args.name}-control-plane",
            metadata={**_namespaced(), "name": f"{args.name}-control-plane"},
            spec={
                "replicas": args.control_plane_replicas,
                "version": args.kubernetes_version,
                "machineTemplate": {
                    "spec": {
                        "infrastructureRef": {
                            "apiGroup": _INFRA_API_GROUP,
                            "kind": "DockerMachineTemplate",
                            "name": _name_of(cp_dmt),
                        }
                    }
                },
                "kubeadmConfigSpec": {
                    "clusterConfiguration": {
                        "apiServer": {"certSANs": CERT_SANS}
                    },
                    "initConfiguration": {
                        "nodeRegistration": {"kubeletExtraArgs": _kubelet_extra_args()}
                    },
                    "joinConfiguration": {
                        "nodeRegistration": {"kubeletExtraArgs": _kubelet_extra_args()}
                    },
                },
            },
            opts=child_opts,
        )

        # KubeadmConfigTemplate (auto-named, replace on spec change)
        kct = capi.bootstrap.v1beta2.KubeadmConfigTemplate(
            f"{args.name}-md-0",
            metadata=_namespaced(),
            spec={
                "template": {
                    "spec": {
                        "joinConfiguration": {
                            "nodeRegistration": {"kubeletExtraArgs": _kubelet_extra_args()}
                        }
                    }
                }
            },
            opts=pulumi.ResourceOptions(parent=self, replace_on_changes=["spec"]),
        )

        # MachineDeployment
        cluster_label = {f"{_CLUSTER_API_GROUP}/cluster-name": args.name}
        md = capi.cluster.v1beta2.MachineDeployment(
            f"{args.name}-md-0",
            metadata={**_namespaced(), "name": f"{args.name}-md-0"},
            spec={
                "clusterName": args.name,
                "replicas": args.worker_replicas,
                "selector": {"matchLabels": cluster_label},
                "template": {
                    "metadata": {"labels": cluster_label},
                    "spec": {
                        "clusterName": args.name,
                        "version": args.kubernetes_version,
                        "bootstrap": {
                            "configRef": {
                                "apiGroup": _BOOTSTRAP_API_GROUP,
                                "kind": "KubeadmConfigTemplate",
                                "name": _name_of(kct),
                            }
                        },
                        "infrastructureRef": {
                            "apiGroup": _INFRA_API_GROUP,
                            "kind": "DockerMachineTemplate",
                            "name": _name_of(worker_dmt),
                        },
                    },
                },
            },
            opts=child_opts,
        )

        # Cluster
        cluster = capi.cluster.v1beta2.Cluster(
            args.name,
            metadata={
                **_namespaced(),
                "name": args.name,
                "labels": {CNI_LABEL_KEY: CNI_LABEL_VALUE},
                "annotations": {
                    "pulumi.com/waitFor": "condition=Available",
                    "pulumi.com/timeoutSeconds": "1200",
                },
            },
            spec={
                "clusterNetwork": {
                    "pods": {"cidrBlocks": [args.pod_cidr]},
                    "services": {"cidrBlocks": [args.service_cidr]},
                    "serviceDomain": "cluster.local",
                },
                "infrastructureRef": {
                    "apiGroup": _INFRA_API_GROUP,
                    "kind": "DockerCluster",
                    "name": _name_of(dc),
                },
                "controlPlaneRef": {
                    "apiGroup": _CONTROLPLANE_API_GROUP,
                    "kind": "KubeadmControlPlane",
                    "name": _name_of(kcp),
                },
            },
            opts=child_opts,
        )

        # CNI — ConfigMap + ClusterResourceSet
        cm = k8s.core.v1.ConfigMap(
            f"{args.name}-cni-kindnet",
            metadata={**_namespaced(), "name": f"{args.name}-cni-kindnet"},
            data={"kindnet.yaml": render_kindnet(args.pod_cidr)},
            opts=child_opts,
        )

        crs = capi.addons.v1beta2.ClusterResourceSet(
            f"{args.name}-cni",
            metadata={**_namespaced(), "name": f"{args.name}-cni"},
            spec={
                "clusterSelector": {"matchLabels": {CNI_LABEL_KEY: CNI_LABEL_VALUE}},
                "resources": [{"kind": "ConfigMap", "name": _name_of(cm)}],
                "strategy": "ApplyOnce",
            },
            opts=child_opts,
        )

        self.cluster_name = _name_of(cluster)
        self.namespace = ns_name
        self.kubeconfig_secret_name = pulumi.Output.concat(args.name, "-kubeconfig")
        self.register_outputs({
            "clusterName": self.cluster_name,
            "namespace": self.namespace,
            "kubeconfigSecretName": self.kubeconfig_secret_name,
        })
